package fold

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// fixturePath is the scene the frontend's kinematics test folds.
//
// It lives next to the test that consumes it, so the two halves of the
// hinge-tree implementation - Go for the geometry, TypeScript for the
// viewer - are held to the same numbers.
const fixturePath = "../../frontend/src/features/fold3d/foldScene.fixture.json"

// fixtureScene is the JSON the frontend test imports.
type fixtureScene struct {
	Description string         `json:"description"`
	Params      Params         `json:"params"`
	FoldedAt    float64        `json:"folded_at"`
	Panels      []fixturePanel `json:"panels"`
}

type fixturePanel struct {
	ID      string  `json:"id"`
	Parent  string  `json:"parent"`
	Hinge   *Hinge  `json:"hinge"`
	TStart  float64 `json:"t_start"`
	TEnd    float64 `json:"t_end"`
	Polygon Polygon `json:"polygon"`
	Folded  Polygon `json:"folded"`
}

// buildFixture folds the default scene at t = 1 and records where every
// panel's vertices end up.
func buildFixture(t *testing.T) fixtureScene {
	t.Helper()

	scene := mustBuild(t, DefaultParams())
	fixture := fixtureScene{
		Description: "Generated by internal/fold/fixture_test.go. Do not edit by hand.",
		Params:      scene.Params,
		FoldedAt:    1,
	}

	for _, panel := range scene.Panels {
		fixture.Panels = append(fixture.Panels, fixturePanel{
			ID:      panel.ID,
			Parent:  panel.Parent,
			Hinge:   panel.Hinge,
			TStart:  panel.TStart,
			TEnd:    panel.TEnd,
			Polygon: panel.Polygon,
			Folded:  scene.FoldedPolygon(panel, 1),
		})
	}
	return fixture
}

// TestFrontendFixtureIsCurrent fails when the engine changed and the
// fixture the frontend test folds was not regenerated.
//
// Regenerate with: UPDATE_FOLD_FIXTURE=1 go test ./internal/fold -run Fixture
func TestFrontendFixtureIsCurrent(t *testing.T) {
	want, err := json.MarshalIndent(buildFixture(t), "", "  ")
	if err != nil {
		t.Fatalf("marshal the fixture: %v", err)
	}
	want = append(want, '\n')

	if os.Getenv("UPDATE_FOLD_FIXTURE") == "1" {
		if err := os.WriteFile(filepath.Clean(fixturePath), want, 0o644); err != nil {
			t.Fatalf("write the fixture: %v", err)
		}
		t.Logf("wrote %s", fixturePath)
		return
	}

	got, err := os.ReadFile(filepath.Clean(fixturePath))
	if err != nil {
		t.Fatalf("read the fixture (run with UPDATE_FOLD_FIXTURE=1 to create it): %v", err)
	}
	if string(got) != string(want) {
		t.Fatal("the frontend fold fixture is stale: run UPDATE_FOLD_FIXTURE=1 go test ./internal/fold -run Fixture")
	}
}
